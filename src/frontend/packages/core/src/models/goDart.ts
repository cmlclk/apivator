import type { ModelClass, ModelEnum, ModelSet, TypeRef } from './ir';
import {
  commentLines,
  fieldIdentifiers,
  header,
  rootTypeNote,
  type GeneratedFile,
  type ModelOptions,
} from './common';
import { camelCase, goName, RESERVED, snakeCase, uniqueName } from './naming';

const rootName = (set: ModelSet) =>
  set.root.kind === 'class' ? set.root.name : (set.types[0]?.name ?? 'models');

/**
 * Go struct'ları (`encoding/json` etiketleriyle). Nullable/opsiyonel skaler ve struct alanlar işaretçi olur;
 * tarih-saat `time.Time`, yalnızca tarih ve UUID `string`. Hizalama gofmt ile aynıdır.
 */
export function generateGo(set: ModelSet, options: ModelOptions): GeneratedFile[] {
  const pkg =
    options.namespace
      ?.trim()
      .replace(/[^A-Za-z0-9_]/g, '_')
      .toLowerCase() || 'models';
  let usesTime = false;
  const typeName = (type: TypeRef): string => {
    switch (type.kind) {
      case 'primitive':
        switch (type.type) {
          case 'datetime':
            usesTime = true;
            return 'time.Time';
          default:
            return {
              string: 'string',
              integer: 'int',
              long: 'int64',
              number: 'float64',
              boolean: 'bool',
              date: 'string',
              uuid: 'string',
              any: 'any',
            }[type.type as 'string'];
        }
      case 'array':
        return `[]${typeName(type.items)}`;
      case 'map':
        return `map[string]${typeName(type.values)}`;
      default:
        return type.name;
    }
  };
  const pointer = (type: TypeRef) =>
    !(type.kind === 'array' || type.kind === 'map' || (type.kind === 'primitive' && type.type === 'any'));

  const renderStruct = (model: ModelClass) => {
    const names = fieldIdentifiers(
      model.fields,
      (n) => goName(n),
      'go',
      (n) => `${n}_`,
    );
    const rows = model.fields.map((f, i) => {
      const optional = f.nullable || f.optional;
      const type = `${optional && pointer(f.type) ? '*' : ''}${typeName(f.type)}`;
      const tag = `\`json:"${f.name.replace(/"/g, '\\"')}${f.optional ? ',omitempty' : ''}"\``;
      return { name: names[i]!, type, tag, doc: commentLines(f.description) };
    });
    // gofmt: alan adı ve tipi sütunlara hizalanır; yorum satırı yeni bir hizalama grubu başlatır.
    const groups: (typeof rows)[] = [];
    for (const row of rows) {
      if (groups.length === 0 || row.doc.length) groups.push([]);
      groups.at(-1)!.push(row);
    }
    return [
      ...commentLines(model.description).map((l) => `// ${l}`),
      `type ${model.name} struct {`,
      ...groups.flatMap((group) => {
        const nameWidth = Math.max(...group.map((r) => r.name.length));
        const typeWidth = Math.max(...group.map((r) => r.type.length));
        return group.flatMap((r) => [
          ...r.doc.map((l) => `\t// ${l}`),
          `\t${r.name.padEnd(nameWidth)} ${r.type.padEnd(typeWidth)} ${r.tag}`,
        ]);
      }),
      '}',
    ];
  };

  const renderEnum = (model: ModelEnum) => {
    const used = new Set<string>();
    const names = model.values.map((v) => uniqueName(`${model.name}${goName(v, 'Value')}`, used));
    const width = Math.max(...names.map((n) => n.length));
    return [
      ...commentLines(model.description).map((l) => `// ${l}`),
      `type ${model.name} string`,
      '',
      'const (',
      ...model.values.map((v, i) => `\t${names[i]!.padEnd(width)} ${model.name} = ${JSON.stringify(v)}`),
      ')',
    ];
  };

  const body: string[] = [];
  for (const type of set.types) {
    if (body.length) body.push('');
    body.push(...(type.kind === 'class' ? renderStruct(type) : renderEnum(type)));
  }
  const rootNote = set.root.kind !== 'class' ? [`// ${rootTypeNote(typeName(set.root))}`, ''] : [];
  const content = [
    `// Code generated by Apivator. DO NOT EDIT.`,
    `// ${header()}`,
    '',
    `package ${pkg}`,
    '',
    ...(usesTime ? ['import "time"', ''] : []),
    ...rootNote,
    ...body,
    '',
  ].join('\n');
  return [{ name: `${snakeCase(rootName(set), 'models')}.go`, content }];
}

/**
 * Dart sınıfları; `fromJson` / `toJson` elle yazılır (build_runner gerekmez). Tarih-saat `DateTime`, tarih ve
 * UUID `String`; enum'lar Dart 2.17+ gelişmiş enum.
 */
export function generateDart(set: ModelSet, options: ModelOptions): GeneratedFile[] {
  void options;
  const dartString = (text: string) =>
    `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;
  const typeName = (type: TypeRef): string => {
    switch (type.kind) {
      case 'primitive':
        return {
          string: 'String',
          integer: 'int',
          long: 'int',
          number: 'double',
          boolean: 'bool',
          date: 'String',
          datetime: 'DateTime',
          uuid: 'String',
          any: 'dynamic',
        }[type.type];
      case 'array':
        return `List<${typeName(type.items)}>`;
      case 'map':
        return `Map<String, ${typeName(type.values)}>`;
      default:
        return type.name;
    }
  };

  /** JSON değerinden Dart değerine (null olmadığı bilinen ifade için). */
  const fromJson = (type: TypeRef, expr: string): string => {
    switch (type.kind) {
      case 'primitive':
        switch (type.type) {
          case 'number':
            return `(${expr} as num).toDouble()`;
          case 'datetime':
            return `DateTime.parse(${expr} as String)`;
          case 'any':
            return expr;
          default:
            return `${expr} as ${typeName(type)}`;
        }
      case 'array':
        return `(${expr} as List<dynamic>).map((e) => ${fromJson(type.items, 'e')}).toList()`;
      case 'map':
        return `(${expr} as Map<String, dynamic>).map((k, v) => MapEntry(k, ${fromJson(type.values, 'v')}))`;
      case 'class':
        return `${type.name}.fromJson(${expr} as Map<String, dynamic>)`;
      case 'enum':
        return `${type.name}.fromJson(${expr} as String)`;
    }
  };
  const toJson = (type: TypeRef, expr: string): string => {
    switch (type.kind) {
      case 'primitive':
        return type.type === 'datetime' ? `${expr}.toIso8601String()` : expr;
      case 'array': {
        const inner = toJson(type.items, 'e');
        return inner === 'e' ? expr : `${expr}.map((e) => ${inner}).toList()`;
      }
      case 'map': {
        const inner = toJson(type.values, 'v');
        return inner === 'v' ? expr : `${expr}.map((k, v) => MapEntry(k, ${inner}))`;
      }
      default:
        return `${expr}.toJson()`;
    }
  };

  const renderClass = (model: ModelClass) => {
    const names = fieldIdentifiers(
      model.fields,
      (n) => camelCase(n),
      'dart',
      (n) => `${n}_`,
      ['fromJson', 'toJson', 'hashCode', 'runtimeType'],
    );
    const lines = [...commentLines(model.description).map((l) => `/// ${l}`), `class ${model.name} {`];
    model.fields.forEach((f, i) => {
      lines.push(...commentLines(f.description).map((l) => `  /// ${l}`));
      lines.push(`  final ${typeName(f.type)}${f.nullable || f.optional ? '?' : ''} ${names[i]};`);
    });
    lines.push('', `  const ${model.name}({`);
    model.fields.forEach((f, i) =>
      lines.push(`    ${f.nullable || f.optional ? '' : 'required '}this.${names[i]},`),
    );
    lines.push('  });', '', `  factory ${model.name}.fromJson(Map<String, dynamic> json) => ${model.name}(`);
    model.fields.forEach((f, i) => {
      const access = `json[${dartString(f.name)}]`;
      const value =
        f.nullable || f.optional
          ? f.type.kind === 'primitive' && f.type.type === 'any'
            ? access
            : `${access} == null ? null : ${fromJson(f.type, access)}`
          : fromJson(f.type, access);
      lines.push(`        ${names[i]}: ${value},`);
    });
    lines.push('      );', '', '  Map<String, dynamic> toJson() => {');
    model.fields.forEach((f, i) => {
      const nullable = f.nullable || f.optional;
      const converted = toJson(f.type, nullable ? `${names[i]}!` : names[i]!);
      const plain = converted === `${names[i]}!` || converted === names[i];
      const value = plain ? names[i] : nullable ? `${names[i]} == null ? null : ${converted}` : converted;
      lines.push(`        ${dartString(f.name)}: ${value},`);
    });
    lines.push('      };', '}');
    return lines;
  };

  const renderEnum = (model: ModelEnum) => {
    const used = new Set<string>(['values', 'index', 'name']);
    const members = model.values.map((v) => {
      const name = camelCase(v, 'value');
      return uniqueName(RESERVED.dart!.has(name) ? `${name}Value` : name, used);
    });
    return [
      ...commentLines(model.description).map((l) => `/// ${l}`),
      `enum ${model.name} {`,
      ...model.values.map(
        (v, i) => `  ${members[i]}(${dartString(v)})${i < model.values.length - 1 ? ',' : ';'}`,
      ),
      '',
      `  const ${model.name}(this.value);`,
      '',
      '  final String value;',
      '',
      `  static ${model.name} fromJson(String value) => values.firstWhere((e) => e.value == value);`,
      '',
      '  String toJson() => value;',
      '}',
    ];
  };

  const body: string[] = [];
  for (const type of set.types) {
    if (body.length) body.push('');
    body.push(...(type.kind === 'class' ? renderClass(type) : renderEnum(type)));
  }
  const rootNote = set.root.kind !== 'class' ? [`// ${rootTypeNote(typeName(set.root))}`, ''] : [];
  return [
    {
      name: `${snakeCase(rootName(set), 'models')}.dart`,
      content: [`// ${header()}`, '', ...rootNote, ...body, ''].join('\n'),
    },
  ];
}
